-- v23. Safe admin-only question reconciliation with an audit log.
-- Never deletes questions or resets member answer history.
BEGIN;
CREATE TABLE IF NOT EXISTS public.quiz_question_revision_log (
  revision_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id text NOT NULL,
  change_kind text NOT NULL CHECK (change_kind IN ('insert','update')),
  prior jsonb,
  revised jsonb NOT NULL,
  changed_by uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  changed_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.quiz_question_revision_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.quiz_question_revision_log FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.quiz_question_revision_log_revision_id_seq FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.quiz_admin_apply_question_changes(p_changes jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path=''
AS $function$
DECLARE
 v_uid uuid := auth.uid();
 v_entry jsonb;
 v_after jsonb;
 v_id text;
 v_mode text;
 v_prior public.quiz_questions%rowtype;
 v_inserted integer := 0;
 v_updated integer := 0;
BEGIN
 IF v_uid IS NULL OR NOT EXISTS (
   SELECT 1 FROM public.quiz_admins a WHERE a.user_id=v_uid
 ) THEN
   RAISE EXCEPTION 'Administrator privileges required' USING ERRCODE='42501';
 END IF;
 IF p_changes IS NULL OR jsonb_typeof(p_changes)<>'array'
    OR jsonb_array_length(p_changes)<1 OR jsonb_array_length(p_changes)>150 THEN
   RAISE EXCEPTION 'Select 1-150 valid changes per batch' USING ERRCODE='22023';
 END IF;
 FOR v_entry IN SELECT value FROM jsonb_array_elements(p_changes) LOOP
   v_mode := v_entry->>'mode';
   v_id := v_entry->>'id';
   v_after := v_entry->'after';
   IF v_id IS NULL OR v_id='' OR v_after IS NULL
       OR jsonb_typeof(v_after)<>'object'
       OR (v_after->>'id') IS DISTINCT FROM v_id THEN
     RAISE EXCEPTION 'Invalid question change payload' USING ERRCODE='22023';
   END IF;

   IF v_mode='insert' THEN
     -- A changed key is NEVER silently treated as the same question.
     INSERT INTO public.quiz_questions (
       id,mansion,category,knowledge_type,difficulty,prompt,options,answer,explanation
     ) VALUES (
       v_id,v_after->>'mansion',v_after->>'category',
       v_after->>'knowledge_type',v_after->>'difficulty',
       v_after->>'prompt',v_after->'options',
       (v_after->>'answer')::integer,v_after->>'explanation'
     );
     INSERT INTO public.quiz_question_revision_log(question_id,change_kind,prior,revised,changed_by)
       VALUES(v_id,'insert',null,v_after,v_uid);
     v_inserted:=v_inserted+1;
   ELSIF v_mode='update' THEN
     SELECT * INTO v_prior FROM public.quiz_questions WHERE id=v_id FOR UPDATE;
     IF NOT FOUND THEN
       RAISE EXCEPTION 'Question % no longer exists; refresh comparison',v_id USING ERRCODE='P0001';
     END IF;
     -- Optimistic conflict detection. Every authored field must still equal the
     -- administrator's preview snapshot, otherwise the entire batch rolls back.
     IF (to_jsonb(v_prior)-'updated_at') IS DISTINCT FROM (v_entry->'before') THEN
       RAISE EXCEPTION 'Question % changed after preview; refresh comparison',v_id USING ERRCODE='P0001';
     END IF;
     UPDATE public.quiz_questions SET
       mansion=v_after->>'mansion',category=v_after->>'category',
       knowledge_type=v_after->>'knowledge_type',difficulty=v_after->>'difficulty',
       prompt=v_after->>'prompt',options=v_after->'options',
       answer=(v_after->>'answer')::integer,explanation=v_after->>'explanation',
       updated_at=now()
     WHERE id=v_id;
     INSERT INTO public.quiz_question_revision_log(question_id,change_kind,prior,revised,changed_by)
       VALUES(v_id,'update',to_jsonb(v_prior)-'updated_at',v_after,v_uid);
     v_updated:=v_updated+1;
   ELSE
     RAISE EXCEPTION 'Invalid change mode' USING ERRCODE='22023';
   END IF;
 END LOOP;
 RETURN jsonb_build_object('inserted',v_inserted,'updated',v_updated,
   'unchanged',0,'audit_logged',v_inserted+v_updated);
END;
$function$;

REVOKE ALL ON FUNCTION public.quiz_admin_apply_question_changes(jsonb) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.quiz_admin_apply_question_changes(jsonb) TO authenticated;
COMMIT;
NOTIFY pgrst, 'reload schema';
